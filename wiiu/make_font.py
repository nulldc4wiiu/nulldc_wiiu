#!/usr/bin/env python3
# Rasterizes Roboto (Apache 2.0, wiiu/Roboto-Regular.ttf) into wiiu/font_roboto.h: ASCII 32-126 as 8-bit coverage
# with proportional metrics, so the picker has an anti-aliased font without a TTF engine or a file on the SD card.
# usage: docker run --rm -v "$PWD/wiiu:/w" wiiu-tools python3 /w/make_font.py [pixel size]
import sys
from PIL import Image, ImageDraw, ImageFont
size = int(sys.argv[1]) if len(sys.argv) > 1 else 24
font = ImageFont.truetype('/w/Roboto-Regular.ttf', size)
ascent, descent = font.getmetrics()
glyphs, data = [], bytearray()
for c in range(32, 127):
    ch = chr(c)
    x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
    w, h = max(x1 - x0, 0), max(y1 - y0, 0)
    off = len(data)
    if w and h:
        img = Image.new('L', (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, fill=255, font=font, anchor='ls')
        data += img.tobytes()
    glyphs.append((off, w, h, x0, y0 + ascent, round(font.getlength(ch))))
with open('/w/font_roboto.h', 'w') as f:
    f.write('// generated by make_font.py from Roboto-Regular.ttf (Apache License 2.0), %d px\n#pragma once\n' % size)
    f.write('static const int FONT_LINE = %d;\n' % (ascent + descent + 2))
    f.write('struct FontGlyph { unsigned offset; signed char w, h, x, y, advance; };\n')
    f.write('static const FontGlyph font_glyphs[95] = {\n')
    for g in glyphs:
        f.write('    { %d, %d, %d, %d, %d, %d },\n' % g)
    f.write('};\nstatic const unsigned char font_alpha[] = {\n')
    for i in range(0, len(data), 24):
        f.write('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
    f.write('};\n')
print('size', size, 'line', ascent + descent + 2, 'bytes', len(data))
