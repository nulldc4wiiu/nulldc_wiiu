# Generates wiiu/presets_generated.cpp from wii/main.cpp: every preset global with its default, and every
# one-line get_*() getter, so the Wii U build reads the same settings as the Wii frontend without its menu.
# usage: python3 wiiu/gen_presets.py   (rerun after merging upstream)
import re, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = open(os.path.join(root, 'wii', 'main.cpp'), encoding='latin-1').read()
var_re = re.compile(r'^(?:volatile\s+)?(int|bool|u32|s32|float|unsigned int|u8|u16)\s+(g_\w+)\s*=\s*([^;]+);', re.M)
get_re = re.compile(r'(int|bool|u32|s32|float|unsigned int)\s+(get_\w+)\s*\(\s*(?:void)?\s*\)\s*\{\s*return\s+([^;]+);\s*\}')
# enum constants used as defaults (e.g. SPECIAL_LAYOUT_OFF) resolve to their value in main.cpp
consts = {}
for body in re.findall(r'enum\s*\w*\s*\{([^}]*)\}', src):
    value = -1
    for item in body.split(','):
        item = re.sub(r'//.*', '', item).strip()
        m = re.match(r'([A-Z_][A-Z0-9_]*)\s*(?:=\s*(-?\w+))?', item)
        if not m:
            continue
        value = int(m.group(2), 0) if m.group(2) else value + 1
        consts[m.group(1)] = value
for name, value in re.findall(r'^#define\s+([A-Z_][A-Z0-9_]*)\s+(-?\d+)\b', src, re.M):
    consts.setdefault(name, int(value))
vars_ = {}
for t, name, init in var_re.findall(src):
    init = re.sub(r'\b[A-Z_][A-Z0-9_]*\b', lambda m: str(consts.get(m.group(0), m.group(0))), init.strip())
    vars_.setdefault(name, (t, init))
getters = {}
for t, name, expr in get_re.findall(src):
    getters.setdefault(name, (t, expr.strip()))
used = set()
for name, (t, expr) in getters.items():
    used.update(re.findall(r'\bg_\w+', expr))
out = ['// Generated by wiiu/gen_presets.py from wii/main.cpp - do not edit.', '#include "types.h"', '', 'extern "C" {']
for name, (t, init) in sorted(vars_.items()):
    out.append(f'{t} {name} = {init};')
out.append('')
skipped = []
for name, (t, expr) in sorted(getters.items()):
    if all(v in vars_ for v in re.findall(r'\bg_\w+', expr)) and not re.search(r'\b(?!g_)[A-Za-z_]\w*\s*\(', expr):
        out.append(f'{t} {name}() {{ return {expr}; }}')
    else:
        skipped.append(name)
out.append('}')
out.append('')
out.append('// name -> int preset, for overrides from sd:/wiiu/nulldc/wiiu.cfg (see main_wiiu.cpp)')
out.append('struct wiiu_preset { const char *name; int *value; };')
out.append('extern const wiiu_preset wiiu_presets[] = {')
for name, (t, init) in sorted(vars_.items()):
    if t == 'int':
        out.append(f'    {{ "{name}", &{name} }},')
out.append('    { nullptr, nullptr },')
out.append('};')
open(os.path.join(root, 'wiiu', 'presets_generated.cpp'), 'w').write('\n'.join(out) + '\n')
print(f'{len(vars_)} globals, {len(getters) - len(skipped)} getters; skipped: {" ".join(skipped)}')
